#!/usr/bin/env python3
"""Copy the license texts of everything the build bundles into licenses/.

    python tools/collect_licenses.py

A frozen exe distributes its dependencies as binary code, and BSD-3/Apache-2.0
require their notices to travel with it. The wheels that ship a LICENSE file
have it in their dist-info; the ones that do not are listed in the index with
their declared license, so the gap is visible instead of silent.
"""
import importlib.metadata as metadata
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'licenses'
LICENSE_NAMES = ('LICENSE', 'LICENSE.txt', 'LICENSE.md', 'LICENCE', 'COPYING',
                 'COPYING.txt', 'NOTICE', 'NOTICE.txt', 'LICENSE-MIT', 'LICENSE-APACHE')


def license_files(dist):
    """Every license-ish file inside a distribution's metadata directory."""
    found = []
    files = dist.files or []
    for entry in files:
        name = entry.name.upper()
        if not any(name == candidate.upper() or name.startswith(candidate.upper() + '.')
                   for candidate in LICENSE_NAMES):
            continue
        if 'license' in str(entry).lower().replace('licenses', 'license') or 'copying' in str(entry).lower() or 'notice' in str(entry).lower():
            found.append(entry)
    return found


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    rows = []
    missing = []
    for dist in sorted(metadata.distributions(), key=lambda d: (d.metadata['Name'] or '').lower()):
        name = dist.metadata['Name'] or 'unknown'
        version = dist.version or '?'
        declared = (dist.metadata.get('License-Expression')
                    or dist.metadata.get('License')
                    or next((c.split('::')[-1].strip() for c in dist.metadata.get_all('Classifier') or []
                             if c.startswith('License ::')), '') or '').strip()
        declared = ' '.join(str(declared).split())[:80]

        target = OUT / name.replace(' ', '_').replace('/', '_')
        copied = []
        for entry in license_files(dist):
            source = Path(dist.locate_file(entry))
            if not source.is_file():
                continue
            target.mkdir(parents=True, exist_ok=True)
            destination = target / source.name
            if destination.exists():
                continue
            shutil.copyfile(source, destination)
            copied.append(source.name)

        if copied:
            rows.append((name, version, declared, ', '.join(sorted(set(copied)))))
        else:
            missing.append((name, version, declared))

    index = ['# Bundled license texts', '',
             'Generated by `tools/collect_licenses.py`; do not edit by hand.', '',
             '| Package | Version | Declared license | File(s) |', '|---|---|---|---|']
    index += [f'| {name} | {version} | {declared or "—"} | {files} |' for name, version, declared, files in rows]
    index += ['', '## No license file shipped by the wheel', '',
              'These declare a license but do not carry its text, so it has to be fetched from the',
              'package source before a public release (see THIRD_PARTY_NOTICES.md).', '']
    index += [f'- **{name}** {version} — {declared or "license not declared"}' for name, version, declared in missing]
    (OUT / 'INDEX.md').write_text('\n'.join(index) + '\n', encoding='utf-8')

    print(f'licenses/: {len(rows)} package(s) with a text, {len(missing)} without')
    for name, version, declared in missing:
        print(f'  no license file: {name} {version} ({declared or "undeclared"})')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
